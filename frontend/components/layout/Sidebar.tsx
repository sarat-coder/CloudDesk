function logout() {
  if (typeof window !== "undefined") {
    localStorage.removeItem("token");
    localStorage.removeItem("role");
    window.location.href = "/login";
  }
}

export function Sidebar({ role, userEmail, userName }: Props) {
  const pathname = usePathname();
  const visibleItems = NAV_ITEMS.filter(
    (item) => !item.adminOnly || role === "admin"
  );

  return (
    <aside className="flex flex-col w-56 min-h-screen border-r border-[var(--border)] bg-[var(--bg-subtle)] shrink-0">
      <div className="px-4 py-5 border-b border-[var(--border)]">
        <span className="text-lg font-semibold text-[var(--brand)]">CloudDesk</span>
        <div className="mt-0.5 text-xs text-[var(--fg-muted)]">Support Console</div>
      </div>

      <nav className="flex-1 py-3 px-2 space-y-0.5">
        {visibleItems.map((item) => {
          const active =
            pathname === item.href ||
            (item.href !== "/dashboard" && pathname.startsWith(item.href));
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-2.5 px-3 py-2 rounded-md text-sm transition-colors ${
                active
                  ? "bg-[var(--brand)] text-white"
                  : "text-[var(--fg-muted)] hover:bg-[var(--border)] hover:text-[var(--fg)]"
              }`}
            >
              {ICONS[item.icon]}
              {item.label}
            </Link>
          );
        })}
      </nav>

      <div className="border-t border-[var(--border)] px-4 py-3">
        <div className="text-xs font-medium text-[var(--fg)]">{userName}</div>
        <div className="text-xs text-[var(--fg-muted)]">{userEmail}</div>
        <div className="mt-1 inline-flex items-center px-1.5 py-0.5 rounded text-xs font-medium bg-[var(--border)] text-[var(--fg-muted)]">
          {role}
        </div>
        <button
          onClick={logout}
          className="mt-2 w-full text-left text-xs text-[var(--fg-muted)] hover:text-[var(--fg)]"
        >
          Sign out
        </button>
      </div>
    </aside>
  );
}
